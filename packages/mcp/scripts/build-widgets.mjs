#!/usr/bin/env node
// Generates src/widgets.generated.ts: the MCP Apps widget sources (widgets/) and the ext-apps
// browser runtime as string constants, so the widgets ship inside the package with no file reads
// at runtime (Workers have no filesystem) and no remote scripts (the host iframe's CSP blocks them).
// The output is gitignored; `build`, `typecheck` and the test setup regenerate it.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(pkg, 'package.json'));

/**
 * The ext-apps `app-with-deps` build is minified ESM ending in `export{a as App,…}`. Inline
 * module scripts cannot import, so its export list becomes a `globalThis.ExtApps` assignment.
 */
export function toGlobalRuntime(bundle) {
  const out = bundle.replace(
    /export\{([^}]+)\};?\s*$/,
    (_, body) =>
      'globalThis.ExtApps={' +
      body
        .split(',')
        .map((pair) => {
          const [local, exported] = pair.split(' as ').map((s) => s.trim());
          return `${exported ?? local}:${local}`;
        })
        .join(',') +
      '};',
  );
  if (out === bundle) throw new Error('ext-apps runtime: no trailing export list to rewrite');
  if (/<\/script/i.test(out)) throw new Error('ext-apps runtime contains a closing script tag');
  return out;
}

export function generate() {
  const runtime = toGlobalRuntime(
    readFileSync(require.resolve('@modelcontextprotocol/ext-apps/app-with-deps'), 'utf8'),
  );
  const read = (f) => readFileSync(join(pkg, 'widgets', f), 'utf8');
  const lines = [
    '// Generated by scripts/build-widgets.mjs from widgets/ and @modelcontextprotocol/ext-apps. Do not edit.',
    `export const EXT_APPS_RUNTIME: string = ${JSON.stringify(runtime)};`,
    `export const WIDGET_CSS: string = ${JSON.stringify(read('widget.css'))};`,
    `export const WIDGET_COMMON: string = ${JSON.stringify(read('common.js'))};`,
    `export const WIDGET_SCRIPTS = { recall: ${JSON.stringify(read('recall.js'))}, memory: ${JSON.stringify(read('memory.js'))} } as const;`,
    '',
  ];
  writeFileSync(join(pkg, 'src', 'widgets.generated.ts'), lines.join('\n'));
}

/** Vitest global setup: tests import the generated module without a prior build. */
export function setup() {
  generate();
}

if (process.argv[1] === fileURLToPath(import.meta.url)) generate();
